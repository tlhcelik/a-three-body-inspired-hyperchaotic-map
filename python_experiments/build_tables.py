def fmt(value, digits):
	return "%.*f" % (digits, _clean(value, digits))


def sci_plain(value, digits=1):
	mantissa, exponent = ("%.*e" % (digits, value)).split("e")
	return "%s\\times10^{%d}" % (mantissa, int(exponent))


def thousands(value):
	return "{:,}".format(int(value)).replace(",", "\\,")


