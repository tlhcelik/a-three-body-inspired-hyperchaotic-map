def expected_false_failures(per_type, alpha=0.01):
	"""Expected number and 95% upper quantile of proportion-test failures for an ideal source (Poisson-binomial)."""
	from scipy.stats import binom
	probs = []
	for row in per_type.values():
		m = row["m"]
		max_fail = int(np.floor(m * (1.0 - row["proportion_lower_bound"]) + 1.0e-9))
		probs.append(1.0 - binom.cdf(max_fail, m, alpha))
	dist = np.array([1.0])
	for p in probs:
		dist = np.convolve(dist, [1.0 - p, p])
	cdf = np.cumsum(dist)
	return float(np.sum(probs)), int(np.searchsorted(cdf, 0.95))


def table_nist():
	data = load_json("nist_protocol.json")["conditions"]
	lines = ["\\begin{tabular}{lccccc}", "\\hline", "\\textbf{Kaynak ve dönüşüm} & \\textbf{$\\lambda_{\\max}$} & \\textbf{\\shortstack{Oran ölçütü\\\\başarısız/tür}} & \\textbf{\\shortstack{Beklenen\\\\{}[\\%95 üst]}} & \\textbf{\\shortstack{Tekdüzelik\\\\başarısız/tür}} & \\textbf{\\shortstack{İlk dizi\\\\geçen/hesap.}} \\\\", "\\hline"]
	macros = []
	for key, label, lam in NIST_ROWS:
		row = data.get(key)
		if row is None:
			continue
		expected, upper = expected_false_failures(row["per_type"])
		fail_prop = row["n_pvalue_types"] - row["proportion_ok_types"]
		fail_unif = row["uniformity_assessed_types"] - row["uniformity_ok_types"]
		first = row["first_sequence_original_45_config"]
		lines.append("%s & %s & $%d/%d$ & $%.1f$ [$%d$] & $%d/%d$ & $%d/%d$ \\\\" % (label, lam, fail_prop, row["n_pvalue_types"], expected, upper, fail_unif, row["uniformity_assessed_types"], first["passed"], first["computed"]))
		if key in ("pcg_lsb", "map_lsb_a5.2", "v3_lsb"):
			lines.append("\\hline")
		name = "vNist" + NIST_MACRO[key]
		macros.append((name + "FailProp", fail_prop))
		macros.append((name + "FailUnif", fail_unif))
		macros.append((name + "Types", row["n_pvalue_types"]))
		macros.append((name + "Expected", "%.1f" % expected))
		macros.append((name + "Upper", upper))
		macros.append((name + "FirstPass", first["passed"]))
		macros.append((name + "FirstComp", first["computed"]))
	lines += ["\\hline", "\\end{tabular}"]
	write("tab_nist_protocol", lines)
	write("numbers_nist", ["\\newcommand{\\%s}{%s}%% nist_protocol.json" % (n, v) for n, v in macros])


