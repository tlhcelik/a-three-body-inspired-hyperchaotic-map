def table_epsilon():
	data = load_json("epsilon_scan.json")
	lines = ["\\begin{tabular}{lcccccc}", "\\hline", "\\textbf{$\\varepsilon_s$} & \\textbf{\\shortstack{Kaotik oran\\\\{}[\\%95 GA]}} & \\textbf{\\shortstack{$\\lambda_{\\max}(0.97)$\\\\{}[çeyrekler]}} & \\textbf{$K(0.97)$} & \\textbf{\\shortstack{Yakın\\\\karşılaşma}} & \\textbf{\\shortstack{Sabit nokta\\\\çökmesi}} & \\textbf{\\shortstack{Mutlak\\\\min. mesafe}} \\\\", "\\hline"]
	for key, row in data["softening"].items():
		eps = float(key)
		eps_text = sci(eps, 0) if eps < 0.05 else "$%.2g$" % eps
		lo, hi = row["chaotic_ratio_wilson95"]
		ratio = "$%.3f$ [$%.2f$, $%.2f$]" % (row["chaotic_ratio"], lo, hi)
		lam = row["reference_a097"]["lambda"]
		cells = [
			eps_text,
			ratio,
			"$%.3f$ [$%.2f$, $%.2f$]" % (_clean(lam["median"], 3), _clean(lam["q1"], 2), _clean(lam["q3"], 2)),
			num(row["reference_a097"]["zero_one_K_median_over_ic"]),
			num(row["close_encounter_trajectory_fraction"]),
			"$%d$" % row["fixed_point_collapse_a_count"],
			sci(row["min_distance_absolute"]),
		]
		if abs(eps - SOFTENING) < 1.0e-12:
			cells = ["{\\bfseries\\boldmath %s}" % cell for cell in cells]
		lines.append(" & ".join(cells) + " \\\\")
	lines += ["\\hline", "\\end{tabular}"]
	write("tab_epsilon_scan", lines)


