def _clean(value, digits):
	"""Round and drop the sign of values that print as zero (avoids '-0.000')."""
	rounded = round(value, digits)
	return 0.0 if rounded == 0 else rounded


def pm(stats, digits=3):
	return "$%.*f \\pm %.*f$" % (digits, _clean(stats["mean"], digits), digits, _clean(stats["sd"], digits))


def num(value, digits=3):
	return "---" if value is None else "$%.*f$" % (digits, _clean(value, digits))


def sci(value, digits=2):
	if value is None:
		return "---"
	mantissa, exponent = ("%.*e" % (digits, value)).split("e")
	return "$%s\\times10^{%d}$" % (mantissa, int(exponent))


def write(name, lines):
	st.ensure_dirs()
	path = os.path.join(st.TABLES_DIR, name + ".tex")
	with open(path, "w", encoding="utf-8") as f:
		f.write("%% generated by python_experiments/build_tables.py -- do not edit by hand\n")
		f.write("\n".join(lines) + "\n")
	print("table", name)


REGIME_TR = {"aperiodic": "aperiyodik", "fixed_point": "sabit nokta"}


def regime_text(regimes):
	parts = []
	for key, count in sorted(regimes.items(), key=lambda kv: -kv[1]):
		label = REGIME_TR.get(key, key.replace("period_", "periyot-"))
		parts.append("%s (%d)" % (label, count))
	return ", ".join(parts)


